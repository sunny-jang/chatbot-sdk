// "상담 챗봇"처럼 상품 이름에 들어간 "상담"·"문의"에는 반응하지 않고, 연락 방법을 묻는 말에만 반응합니다.
export function isContactQuestion(message: string) {
  return /연락처|문의처|연락\s*(방법|드리|하려|할\s*수)|문의\s*(방법|하려|할\s*수|드리|하고\s*싶)|(상담|견적)\s*(신청|요청|받고|받을|받으려|하고\s*싶|원해)|전화\s*번호|전화\s*(상담|문의|드리|해도|하려)|휴대폰|핸드폰|이메일|메일\s*주소|담당자.*(연결|번호|연락)/.test(message);
}
